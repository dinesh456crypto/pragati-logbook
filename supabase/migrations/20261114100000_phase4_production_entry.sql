-- Phase 4: Production Entry.
--
--   * One row per production entry: Draft or Submitted. Job details are stored as
--     a snapshot, so later changes to the Production Plan never rewrite history.
--   * Every save goes through save_production_entry(), which checks permissions,
--     machine access and all business rules on the server:
--       - one draft per machine;
--       - print sides: O/S alone, F/S + B/S, or B/B F + B/B B (never mixed);
--       - a closed side, or a fully closed order, takes no new entries;
--       - continuing jobs need an earlier entry for the same order, side and machine;
--       - changeover is required unless the job is continuing, or for a B/B entry
--         that is not the first entry of its order;
--       - unit colours come from the job's colours, each used once;
--       - production date follows the shift rule (B shift before 08:00 belongs to
--         the previous day);
--       - entries on one machine never overlap in time;
--       - Total Given Sheets = OK + Separate + all wastage rows, exactly.
--   * Saves are safe to retry: the same save id never applies twice, and an edit
--     based on an out-of-date copy is refused.

-- Minutes between two moments; empty when either is missing or the end is earlier.
create or replace function public.minutes_between(p_start timestamptz, p_end timestamptz)
returns integer
language sql
immutable
set search_path = ''
as $$
  select case when p_start is not null and p_end is not null and p_end >= p_start
              then round(extract(epoch from (p_end - p_start)) / 60)::integer end;
$$;

-- Plant production date for a moment: B shift time before 08:00 belongs to the previous day.
create or replace function public.plant_production_date(p_at timestamptz, p_shift text)
returns date
language sql
stable
set search_path = ''
as $$
  select case
    when p_shift = 'B' and (p_at at time zone 'Asia/Kolkata')::time < time '08:00'
      then (p_at at time zone 'Asia/Kolkata')::date - 1
    else (p_at at time zone 'Asia/Kolkata')::date
  end;
$$;

-- Print side families: O/S stands alone; F/S pairs with B/S; B/B F pairs with B/B B.
create or replace function public.side_family(p_side text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when p_side = 'O/S' then 'OS'
    when p_side in ('F/S', 'B/S') then 'FB'
    when p_side in ('B/B F', 'B/B B') then 'BB'
  end;
$$;

create table public.production_entries (
  id uuid primary key default gen_random_uuid(),
  entry_no bigint generated by default as identity unique,
  status text not null default 'draft' check (status in ('draft', 'submitted')),

  -- Section 1: job details (snapshot of the plan, editable per entry)
  machine_id uuid not null references public.machines (id) on delete restrict,
  production_date date not null,
  shift text check (shift in ('A', 'B')),
  order_no text check (order_no is null or length(btrim(order_no)) between 1 and 60),
  order_key text generated always as (lower(btrim(order_no))) stored,
  job_id uuid references public.production_jobs (id) on delete restrict,
  job_name text check (job_name is null or length(btrim(job_name)) between 1 and 150),
  category text check (category is null or length(btrim(category)) between 1 and 80),
  ups integer check (ups > 0),
  job_type text check (job_type in ('NPD', 'NEW', 'Re-Print')),
  paper_type_id uuid references public.paper_types (id) on delete restrict,
  planned_quantity integer check (planned_quantity > 0),
  planned_colours text[] not null default '{}' check (public.planned_colours_valid(planned_colours)),
  print_side text check (print_side in ('O/S', 'F/S', 'B/S', 'B/B F', 'B/B B')),
  continuing boolean not null default false,
  continues_entry_id uuid references public.production_entries (id) on delete restrict,

  -- Section 2: workers
  operator_id uuid references public.operators (id) on delete restrict,
  supervisor_id uuid references public.supervisors (id) on delete restrict,
  qc_executive_id uuid references public.qc_executives (id) on delete restrict,
  helpers integer check (helpers between 1 and 4),

  -- Section 3: unit-wise colours (Unit 1..7; empty units are null)
  unit_colours text[] not null default array[null, null, null, null, null, null, null]::text[]
    check (cardinality(unit_colours) = 7),
  coating_id uuid references public.coatings (id) on delete restrict,
  colour_changes integer check (colour_changes between 0 and 7),
  coating_changed boolean,

  -- Sections 4 and 5: changeover activities and production run (actual moments)
  make_ready_start timestamptz,
  make_ready_end timestamptz,
  registration_start timestamptz,
  registration_end timestamptz,
  colour_matching_start timestamptz,
  colour_matching_end timestamptz,
  run_start timestamptz,
  run_end timestamptz,
  make_ready_minutes integer generated always as (public.minutes_between(make_ready_start, make_ready_end)) stored,
  registration_minutes integer generated always as (public.minutes_between(registration_start, registration_end)) stored,
  colour_matching_minutes integer generated always as (public.minutes_between(colour_matching_start, colour_matching_end)) stored,
  -- Machine changeover = earliest activity start to latest activity end (activities
  -- can run in parallel, so their durations are not added up).
  changeover_minutes integer generated always as (public.minutes_between(
    least(
      case when make_ready_end >= make_ready_start then make_ready_start end,
      case when registration_end >= registration_start then registration_start end,
      case when colour_matching_end >= colour_matching_start then colour_matching_start end),
    greatest(
      case when make_ready_end >= make_ready_start then make_ready_end end,
      case when registration_end >= registration_start then registration_end end,
      case when colour_matching_end >= colour_matching_start then colour_matching_end end))) stored,
  run_minutes integer generated always as (public.minutes_between(run_start, run_end)) stored,

  -- Section 6: production quantities
  machine_speed integer check (machine_speed between 0 and 100000),
  total_sheets integer check (total_sheets between 1 and 10000000),
  ok_sheets integer check (ok_sheets between 0 and 10000000),
  separate_sheets integer check (separate_sheets between 0 and 10000000),
  wastage_sheets integer not null default 0 check (wastage_sheets >= 0),
  remarks text check (remarks is null or length(remarks) <= 1000),

  submitted_at timestamptz,
  submitted_by uuid references public.profiles (id) on delete set null,
  last_save_id uuid,
  created_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id) on delete set null
);

