-- Entry users see their machines' entries; dashboard and report users see
-- submitted entries for their machines.
create policy production_entries_select on public.production_entries
  for select to authenticated
  using (
    (select public.can_use_machine(machine_id))
    and (
      (select public.has_perm('production_entry', 'view'))
      or (status = 'submitted' and ((select public.has_perm('production_log', 'view'))
                                    or (select public.has_perm('dashboard', 'view'))))
    )
  );

-- Delete: users with the Delete right; anyone may delete their own draft.
create policy production_entries_delete on public.production_entries
  for delete to authenticated
  using (
    (select public.can_use_machine(machine_id))
    and (
      (select public.has_perm('production_entry', 'delete'))
      or (status = 'draft' and created_by = (select auth.uid()) and (select public.has_perm('production_entry', 'create')))
    )
  );

create policy production_entry_wastage_select on public.production_entry_wastage
  for select to authenticated
  using (exists (select 1 from public.production_entries e where e.id = entry_id));

create policy order_side_closures_select on public.order_side_closures
  for select to authenticated
  using ((select public.has_perm('production_entry', 'view')) or (select public.has_perm('production_log', 'view')));

